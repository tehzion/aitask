import { expect, test } from '@playwright/test';
for (const locale of ['en', 'zh']) test(`monthly payment records and revision details (${locale})`, async ({ page }) => {
  await page.addInitScript(value => localStorage.setItem('aitask:locale', value), locale);
  await page.clock.install({ time: new Date('2026-10-15T04:00:00Z') });
  await page.goto('/login');
  const seed = await page.evaluate(async () => {
    const { useStore } = await import('/src/store/index.ts');
    const { enablePasswordResetBypass } = await import('/src/lib/auth.ts');
    const state = useStore.getState(); const boss = state.users.find(user => user.isSuperAdmin)!;
    enablePasswordResetBypass(boss.id);
    localStorage.setItem(`aitask:release-notice:2026-10-project-workflows:${boss.id}`, 'acknowledged');
    localStorage.setItem(`aitask:release-notice:2026-11-everyday-saves:${boss.id}`, 'acknowledged');
    useStore.setState({ currentUser: { ...boss, mustResetPassword: false }, clients: [], clientPlans: [], tasks: [], projects: [], serviceCycles: [], serviceCyclePayments: [], servicePricingSnapshots: [], deliverables: [], backend: { ...state.backend, mode: 'local', status: 'local', hasLocalChanges: false, pendingMutations: 0 } });
    const created = useStore.getState().createClientWithPlan({ clientName: 'Receipt Co', planName: 'Monthly Design', origin: 'custom', serviceItems: [{ id: 'fee', name: 'Design', platforms: [], unit: 'month', quantity: 1, unitPriceMinor: 10000 }], startDate: '2026-09-01', billingDay: 1, discountType: 'percent', discountValue: 1000, taxRateBps: 600 });
    useStore.getState().activateClientPlan(created.planId!);
    useStore.getState().generateDueLocalServiceCycles();
    return { clientId: created.clientId!, planId: created.planId!, bossId: boss.id, bossName: boss.name };
  });
  await page.goto(`/clients/${seed.clientId}`);
  const zh = locale === 'zh';
  await page.getByRole('tab', { name: zh ? '方案与交付' : 'Plan & delivery', exact: true }).click();
  const overview = page.getByRole('region', { name: zh ? '每月更新安排' : 'Monthly update schedule' });
  const table = overview.getByRole('table');
  await expect(table.getByRole('columnheader').nth(3)).toHaveText(zh ? '付款' : 'Payment');
  const row = table.getByRole('row').nth(1);
  await expect(row).toContainText(zh ? '未记录' : 'Not recorded');
  await row.getByRole('button', { name: zh ? '部分付款' : 'Half payment', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel(zh ? '金额（马币）' : 'Amount (MYR)')).toHaveValue('47.70');
  await dialog.getByLabel(zh ? '金额（马币）' : 'Amount (MYR)').fill('20.00');
  await dialog.getByRole('button', { name: zh ? '记录付款' : 'Record payment', exact: true }).click();
  await expect(dialog).toContainText('20.00');
  await expect(dialog).toContainText(`${zh ? '记录人' : 'Recorded by'} ${seed.bossName}`);
  await expect(dialog).toContainText(zh ? '2026年10月15日' : '15 Oct 2026');
  await expect(dialog).not.toContainText(seed.bossId);
  await dialog.getByRole('button', { name: zh ? '关闭' : 'Close', exact: true }).click();
  await expect(row).toContainText(zh ? '部分已付' : 'Partly paid');
  await row.getByRole('button', { name: zh ? '付款记录' : 'Payment records', exact: true }).click();
  await dialog.getByRole('button', { name: zh ? '全额付款' : 'Full payment', exact: true }).click();
  await expect(dialog.getByLabel(zh ? '金额（马币）' : 'Amount (MYR)')).toHaveValue('75.40');
  await dialog.getByRole('button', { name: zh ? '记录付款' : 'Record payment', exact: true }).click();
  await expect(dialog).toContainText('75.40');
  await dialog.getByRole('button', { name: zh ? '关闭' : 'Close', exact: true }).click();
  await expect(row).toContainText(zh ? '全额付款' : 'Full payment');
  await overview.getByRole('button', { name: zh ? '编辑详情' : 'Edit details', exact: true }).click();
  const editor = page.getByRole('dialog', { name: zh ? '编辑详情' : 'Edit details' });
  await expect(editor.getByLabel(zh ? '方案名称' : 'Plan name', { exact: true })).toHaveValue('Monthly Design');
  await editor.getByLabel(zh ? '方案名称' : 'Plan name', { exact: true }).fill('Future Design');
  await editor.getByRole('button', { name: zh ? '保存草稿' : 'Save draft', exact: true }).click();
  await expect(editor).toContainText(zh ? '草稿已保存' : 'Draft saved');
  await editor.getByRole('button', { name: zh ? '关闭' : 'Close', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(table).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store/index.ts');
    const { defaultRolePermissions } = await import('/src/lib/access.ts');
    const user = useStore.getState().currentUser!;
    useStore.setState({ currentUser: { ...user, isSuperAdmin: false, role: 'Project Manager', permissions: { ...defaultRolePermissions['Project Manager'], viewServicePrices: false, manageClientPlans: false } } });
  });
  await expect(overview.getByRole('button', { name: zh ? '编辑详情' : 'Edit details', exact: true })).toHaveCount(0);
  await expect(table.getByText(zh ? '已收总额' : 'Total received', { exact: false })).toHaveCount(0);
  await expect(table.getByRole('button', { name: zh ? '部分付款' : 'Half payment', exact: true })).toHaveCount(0);
});
