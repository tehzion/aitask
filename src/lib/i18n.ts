export const translateUiText = (value: string, locale: AppLocale) => {
  if (locale !== 'zh' || !value) return value;
  const core = value.trim();
  const translated = zhCopy[core] || zhCopyExtras[core] || zhCopyAdditions[core] || zhSystemCopy[core] || translatePattern(core);
  return translated === core ? value : preserveWhitespace(value, translated);
};

export const getInitialLocale = (): AppLocale => {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = window.localStorage.getItem(APP_LOCALE_STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch {
    // Browser storage is optional; the browser locale remains a sensible fallback.
  }
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
};
