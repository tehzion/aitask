export type MessageId = keyof typeof enMessages;
export type MessageDescriptor = { id: MessageId; values?: MessageValues };
export type UiMessage = MessageDescriptor;

const interpolate = (template: string, values: MessageValues = {}) => template.replace(/\{(\w+)\}/g, (match, key: string) => (
  Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
));

export const msg = (id: MessageId, values?: MessageValues): MessageDescriptor => ({ id, values });

export const formatMessage = (descriptor: MessageDescriptor, locale: AppLocale): string => {
  const template = locale === 'zh' ? zhMessages[descriptor.id] : enMessages[descriptor.id];
  return interpolate(template, descriptor.values);
};

export const messageCatalog = { en: enMessages, zh: zhMessages } as const;
export const messageIds = Object.keys(enMessages) as MessageId[];
export const isMessageId = (value: string): value is MessageId => Object.prototype.hasOwnProperty.call(enMessages, value);

export const getMessagePlaceholders = (value: string): string[] => (
  [...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort()
);

